def main():
    parser = argparse.ArgumentParser(description='Extract ERP phase 1 sources in a chosen folder (offline).')
    parser.add_argument('--dir', default='.', help='Destination folder (default: current directory)')
    parser.add_argument('--force', action='store_true', help='Overwrite conflicting existing project files')
    args = parser.parse_args()
    dest = pathlib.Path(args.dir).expanduser().resolve()
    if sys.version_info < (3, 9):
        raise SystemExit('Python >= 3.9 is required.')
    payload = base64.b64decode(''.join(PAYLOAD.split()))
    with zipfile.ZipFile(io.BytesIO(payload)) as archive:
        entries = [(pathlib.PurePosixPath(name), archive.read(name))
                   for name in archive.namelist() if not name.endswith('/')]
    for name, _ in entries:
        if name.is_absolute() or '..' in name.parts:
            raise SystemExit('Blocked unsafe archive path: ' + str(name))
    conflicts = []
    for name, data in entries:
        path = dest.joinpath(*name.parts)
        if path.is_symlink() or (path.exists() and (not path.is_file() or path.read_bytes() != data)):
            conflicts.append(str(path))
    if conflicts and not args.force:
        print('Refusing to overwrite modified/existing files:')
        for item in conflicts[:20]:
            print('  -', item)
        print('Choose a new --dir or use --force to overwrite project files.')
        raise SystemExit(2)
    for name, data in entries:
        path = dest.joinpath(*name.parts)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
    subprocess.run([sys.executable, str(dest / 'scripts' / 'init_env.py')], check=True)
    print('ERP Phase 1 created at:', dest)
    print('Source files:', len(entries))
    print('Next: cd', dest)
    print('      docker compose up -d --build')
    print('      python scripts/smoke_test.py   # after containers start')
    print('Admin password is in .env; do not commit or share it.')

if __name__ == '__main__':
    main()
